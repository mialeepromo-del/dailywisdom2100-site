const grid = document.getElementById("dealGrid");
const searchInput = document.getElementById("searchInput");
const categoryFilter = document.getElementById("categoryFilter");
const dealCount = document.getElementById("dealCount");
const emptyState = document.getElementById("emptyState");
const yearElement = document.getElementById("year");

function isDealExpired(deal) {
  if (!deal.expiryDate) {
    return false;
  }

  const today = new Date();
  today.setHours(0, 0, 0, 0);

  const expiryDateParts = deal.expiryDate.split("-").map(Number);

  const expiry = new Date(
    expiryDateParts[0],
    expiryDateParts[1] - 1,
    expiryDateParts[2],
    23,
    59,
    59,
    999
  );

  return today > expiry;
}

function getDealImage(deal) {
  if (deal.image) {
    return `
      <img
        src="${deal.image}"
        alt="${deal.title}"
        class="deal-photo"
        loading="lazy"
      >
    `;
  }

  return `
    <span class="deal-emoji" aria-hidden="true">
      ${deal.emoji || "✨"}
    </span>
  `;
}

function hasActiveDealLink(deal) {
  return (
    deal.affiliateLink &&
    deal.affiliateLink !== "#affiliate-link-placeholder"
  );
}

function getDealButton(deal) {
  const expired = isDealExpired(deal);

  if (expired) {
    return `
      <button
        type="button"
        class="deal-button placeholder expired-button"
        disabled
      >
        Expired
      </button>
    `;
  }

  if (hasActiveDealLink(deal)) {
    return `
      <a
        href="${deal.affiliateLink}"
        class="deal-button"
        target="_blank"
        rel="noopener noreferrer"
      >
        Get This Deal
      </a>
    `;
  }

  return `
    <button
      type="button"
      class="deal-button placeholder"
      disabled
    >
      Link Coming Soon
    </button>
  `;
}

function getDealStatusText(deal) {
  if (isDealExpired(deal)) {
    return "Offer ended";
  }

  if (!hasActiveDealLink(deal)) {
    return "Link coming soon";
  }

  return "View deal";
}

function renderDeals() {
  const search = searchInput.value.toLowerCase().trim();
  const category = categoryFilter.value;

  const filtered = deals
  .filter(deal => {
    const searchableText = `
      ${deal.title}
      ${deal.category}
      ${deal.benefit || ""}
      ${deal.description}
      ${deal.code}
      ${deal.expires || ""}
    `.toLowerCase();

    const matchesSearch =
      searchableText.includes(search);

    const matchesCategory =
      category === "all" ||
      deal.category === category;

    return matchesSearch && matchesCategory;
  })

  .sort((a, b) => {
    const aExpired = isDealExpired(a);
    const bExpired = isDealExpired(b);

    // Active 딜은 위, expired 딜은 아래
    if (aExpired !== bExpired) {
      return aExpired ? 1 : -1;
    }

    // 같은 상태에서는 최신 posting이 위
    const aDate = a.postingDate
      ? new Date(a.postingDate + "T00:00:00")
      : new Date(0);

    const bDate = b.postingDate
      ? new Date(b.postingDate + "T00:00:00")
      : new Date(0);

    return bDate - aDate;
  });

  grid.innerHTML = filtered
    .map(deal => {
      const expired = isDealExpired(deal);

      return `
        <article class="deal-card ${expired ? "expired" : ""}">
          <div class="deal-image">
            ${getDealImage(deal)}

            <span class="badge">
              ${deal.benefit}
            </span>

            ${
              expired
                ? `
                  <div
                    class="expired-stamp"
                    aria-label="This offer has expired"
                  >
                    EXPIRED
                  </div>
                `
                : ""
            }
          </div>

          <div class="deal-body">
            <div class="deal-meta">
              <span>${deal.category}</span>
              <span>${deal.posted}</span>
            </div>

            <h3 class="deal-title">
              ${deal.title}
            </h3>

            <p class="deal-description">
              ${deal.description}
            </p>

            <div class="code-box">
              <code>${deal.code}</code>

              <button
                type="button"
                class="copy-btn"
                data-code="${deal.code}"
                ${expired ? "disabled" : ""}
              >
                ${expired ? "Expired" : "Copy"}
              </button>
            </div>

            <div class="deal-meta">
              <span>
                ${expired ? "Expired" : deal.expires}
              </span>

              <span>
                ${getDealStatusText(deal)}
              </span>
            </div>

            ${getDealButton(deal)}
          </div>
        </article>
      `;
    })
    .join("");

  dealCount.textContent =
    `${filtered.length} deal${filtered.length === 1 ? "" : "s"}`;

  emptyState.hidden = filtered.length !== 0;
}

searchInput.addEventListener("input", renderDeals);
categoryFilter.addEventListener("change", renderDeals);

document.querySelectorAll(".category-card").forEach(button => {
  button.addEventListener("click", () => {
    categoryFilter.value = button.dataset.category;
    renderDeals();

    document
      .getElementById("latest")
      .scrollIntoView({ behavior: "smooth" });
  });
});

document.addEventListener("click", async event => {
  if (!event.target.matches(".copy-btn")) {
    return;
  }

  if (event.target.disabled) {
    return;
  }

  const code = event.target.dataset.code;

  try {
    await navigator.clipboard.writeText(code);

    const originalText = event.target.textContent;
    event.target.textContent = "Copied";

    setTimeout(() => {
      event.target.textContent = originalText;
    }, 1200);
  } catch {
    alert(`Code: ${code}`);
  }
});

if (yearElement) {
  yearElement.textContent = new Date().getFullYear();
}

renderDeals();
